"""Assert that every distribution ships the compiled frontend (and the package data).

Usage: python scripts/check_dist.py [dist_dir] [--rebuild-from-sdist]

``src/mecha/static/`` is generated by ``vite build`` and git-ignored. A wheel *or* sdist
without it would install a Mecha without its interface, so a release must not go out.
``--rebuild-from-sdist`` also builds a wheel from the sdist alone, in a clean temporary
directory with no ``web/`` and no Node, as anyone installing from the sdist would.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tarfile
import tempfile
import zipfile
from pathlib import Path

REQUIRED = (
    "mecha/static/index.html",
    "mecha/data/detect_patterns.toml",
    "mecha/data/capabilities.toml",
    "mecha/store/migrations/001_initial.sql",
    "mecha/store/migrations/002_credential_facts.sql",
    "mecha/store/migrations/003_exposures.sql",
)
ASSETS = "mecha/static/assets/"


def missing_in(names: set[str]) -> list[str]:
    missing = [n for n in REQUIRED if n not in names]
    if not any(n.startswith(ASSETS) for n in names):
        missing.append(ASSETS + "*")
    return missing


def wheel_names(path: Path) -> set[str]:
    with zipfile.ZipFile(path) as z:
        return set(z.namelist())


def sdist_names(path: Path) -> set[str]:
    """``mecha_keys-X.Y.Z/src/mecha/static/index.html`` -> ``mecha/static/index.html``."""
    out = set()
    with tarfile.open(path) as t:
        for name in t.getnames():
            parts = name.split("/", 2)
            if len(parts) == 3 and parts[1] == "src":
                out.add(parts[2])
    return out


def check(label: str, names: set[str]) -> bool:
    missing = missing_in(names)
    if missing:
        print(f"error: {label} is missing {', '.join(missing)}", file=sys.stderr)
        return False
    count = sum(n.startswith("mecha/static/") for n in names)
    print(f"ok: {label} ships the frontend ({count} files under mecha/static/)")
    return True


def rebuild_from_sdist(sdist: Path) -> bool:
    uv = shutil.which("uv")
    if uv is None:
        print("error: uv is needed for --rebuild-from-sdist", file=sys.stderr)
        return False
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        with tarfile.open(sdist) as t:
            t.extractall(work, filter="data")
        [root] = [p for p in work.iterdir() if p.is_dir()]
        if (root / "web").exists():
            print("error: the sdist must not need the frontend sources", file=sys.stderr)
            return False
        out = work / "out"
        subprocess.run(  # noqa: S603 - fixed arguments
            [uv, "build", "--wheel", "--out-dir", str(out), str(root)],
            check=True,
            capture_output=True,
        )
        wheels = sorted(out.glob("*.whl"))
        if len(wheels) != 1:
            print("error: rebuilding from the sdist produced no wheel", file=sys.stderr)
            return False
        return check(f"wheel rebuilt from {sdist.name}", wheel_names(wheels[0]))


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dist = Path(args[0] if args else "dist")
    wheels = sorted(dist.glob("mecha_keys-*.whl"))
    sdists = sorted(dist.glob("mecha_keys-*.tar.gz"))
    if not wheels or not sdists:
        print(f"error: need both a wheel and an sdist in {dist}/", file=sys.stderr)
        return 1
    ok = all(check(w.name, wheel_names(w)) for w in wheels)
    ok = all(check(s.name, sdist_names(s)) for s in sdists) and ok
    if "--rebuild-from-sdist" in sys.argv:
        ok = all(rebuild_from_sdist(s) for s in sdists) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
