"""Generate samples/sample-registry.js from the static sample JSON files.

The collection page always fetches with window.fetch first. Browsers that block
fetch() on file:// origins (Chromium) need an offline fallback so the local
samples can still be opened directly; this script embeds the exact JSON payloads
and their byte lengths into a registry keyed by relative URL.

Run from the repository root:  python -I tools/gen_registry.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SAMPLES = ROOT / "samples"
DATA = SAMPLES / "data"

# URLs that intentionally do not resolve must NOT appear in the registry.
REGISTRY_FILES = [
    "line-status.json",
    "output.json",
    "quality.json",
    "equipment.json",
    "equipment-oversize.json",
]

MANIFEST_FILES = [
    "manifest-all-success.json",
    "manifest-optional-fail.json",
    "manifest-all-fail.json",
    "manifest-empty.json",
]

registry = {}
for name in REGISTRY_FILES:
    raw = (DATA / name).read_bytes()
    registry[f"data/{name}"] = {
        "bytes": len(raw),
        "json": json.loads(raw.decode("utf-8")),
    }

manifests = {}
for name in MANIFEST_FILES:
    manifests[name] = json.loads((SAMPLES / name).read_text(encoding="utf-8"))
registry["__manifests"] = manifests

out = SAMPLES / "sample-registry.js"
body = json.dumps(registry, ensure_ascii=False, indent=2)
out.write_text(
    "/* Auto-generated by tools/gen_registry.py - do not edit by hand. */\n"
    "/* Used only as a fallback when window.fetch cannot read file:// URLs. */\n"
    "window.SAMPLE_REGISTRY = " + body + ";\n",
    encoding="utf-8",
)
print(f"wrote {out.relative_to(ROOT)} with {len(REGISTRY_FILES)} data entries + {len(MANIFEST_FILES)} manifests")
for key, val in registry.items():
    if key == "__manifests":
        print(f"  __manifests: {len(val)} manifest(s)")
    else:
        print(f"  {key}: {val['bytes']} bytes")
